// site/scripts/link-node_modules.mjs
// VitePress 内容源在仓库根的 articles/（srcDir: ../articles，位于站点工程根 site/ 之外）。
// Vite 解析裸模块（如 vue）时从内容文件的真实目录向上查找 node_modules，
// 而 node_modules 装在 site/ 里，不是 articles/ 的祖先，导致构建报
// "failed to resolve import vue"。
// 解决办法：在仓库根建一个 node_modules 联接（junction / symlink）指向 site/node_modules，
// 这样从 articles/ 向上能找到它。该联接由 package.json 的 postinstall 自动建立，克隆后 npm install 即生效。
// 联接本身被 .gitignore 的 node_modules/ 忽略，不入库。

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execSync } from 'node:child_process'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const siteRoot = path.resolve(scriptDir, '..')
const repoRoot = path.resolve(siteRoot, '..')
const linkPath = path.join(repoRoot, 'node_modules')
const target = path.join(siteRoot, 'node_modules')

function main() {
  if (!fs.existsSync(target)) {
    console.warn('[link-node_modules] site/node_modules 不存在，请先执行 npm install；本次跳过建立联接')
    return
  }
  if (fs.existsSync(linkPath)) {
    let real = null
    try {
      real = fs.realpathSync(linkPath)
    } catch {
      real = null
    }
    if (real === fs.realpathSync(target)) {
      console.log('[link-node_modules] 仓库根 node_modules 联接已就位')
      return
    }
    // 指向错误的旧联接，重建
    try {
      fs.rmSync(linkPath, { recursive: true, force: true })
    } catch {
      /* ignore */
    }
  }
  fs.mkdirSync(path.dirname(linkPath), { recursive: true })
  if (process.platform === 'win32') {
    execSync(`mklink /J "${linkPath}" "${target}"`, { stdio: 'inherit' })
  } else {
    fs.symlinkSync(target, linkPath, 'dir')
  }
  console.log('[link-node_modules] 已创建 仓库根/node_modules -> site/node_modules 联接')
}

main()
